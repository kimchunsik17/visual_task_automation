def _graph(data, payload, scenario="success"):
    graph = {"nodes": [{"id": "w1", "type": "webhookNode", "data": {}}, {"id": "s1", "type": "osvScanNode", "data": data},
                       {"id": "o1", "type": "outputNode", "data": {}}],
             "edges": [{"id": "e1", "source": "w1", "target": "s1"}, {"id": "e2", "source": "s1", "target": "o1"}]}
    result = mock_service.run(graph, db=None, project_id=1, entry_node_id="w1", payload=payload, scenario=scenario)
    return result, next(s for s in result["logs"] if s.get("node_id") == "s1")


def test_목업_그래프에서_직전_출력의_lockfile_을_읽고_취약점을_결과로_준다():
    result, step = _graph({}, PACKAGE_LOCK_V3)
    assert result["success"] is True, result["result"]
    out = json.loads(step["result_data"])
    assert out["format"] == "package-lock" and out["alertCount"] >= 1 and out["alerts"][0]["package"] == "lodash"
    assert out["alerts"][0]["severity"] == "HIGH" and out["alerts"][0]["fixedVersion"] == "4.17.21" and step.get("error") is None
    assert [q["method"] for q in result["requests"]][:1] == ["POST"]


def test_failOnVulnerable_이면_OSV_VULNERABLE_로_error_갈래():
    _, step = _graph({"failOnVulnerable": True}, PACKAGE_LOCK_V3)
    assert (step.get("error") or {}).get("code") == "OSV_VULNERABLE"
    _, unrecognized = _graph({}, "그냥 텍스트")
    assert (unrecognized.get("error") or {}).get("code") == "OSV_LOCKFILE_UNRECOGNIZED"
    _, down = _graph({}, PACKAGE_LOCK_V3, scenario="server_error")
    assert (down.get("error") or {}).get("code") not in (None, "OSV_VULNERABLE"), "서버 오류는 커넥터 오류로 남는다"
